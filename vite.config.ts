import inertia from '@inertiajs/vite';
import { wayfinder } from '@laravel/vite-plugin-wayfinder';
import babel from '@rolldown/plugin-babel';
import tailwindcss from '@tailwindcss/vite';
import react, { reactCompilerPreset } from '@vitejs/plugin-react';
import laravel from 'laravel-vite-plugin';
import { google } from 'laravel-vite-plugin/fonts';
import { defineConfig, lazyPlugins } from 'vite-plus';

export default defineConfig({
    plugins: lazyPlugins(() => [
        laravel({
            input: ['resources/css/app.css', 'resources/js/app.tsx'],
            refresh: true,
            // Downloaded from Google Fonts at build time and served from our own domain,
            // so visitors' browsers never contact a font CDN (GDPR). Google rather than
            // Bunny because it sends only WOFF2 and splits Noto Sans KR into small slices.
            fonts: [
                // Cyrillic for Russian names and sources in posts (e.g. Пхеньян). Without it
                // those letters fall back to Noto Sans KR, whose Cyrillic looks too large.
                // Its files load only on pages that contain Cyrillic.
                google('Inter', {
                    weights: [400, 500, 600, 700],
                    subsets: ['latin', 'latin-ext', 'cyrillic', 'cyrillic-ext'],
                    preload: [{ weight: 400 }],
                }),
                google('Space Grotesk', {
                    weights: [700],
                    subsets: ['latin', 'latin-ext'],
                    preload: false,
                }),
                // About 100 slices per weight; browsers fetch only the slices whose
                // characters appear on the page.
                google('Noto Sans KR', {
                    weights: [400, 500, 700],
                    subsets: ['korean'],
                    preload: false,
                    optimizedFallbacks: false,
                }),
            ],
        }),
        inertia(),
        react(),
        babel({
            presets: [reactCompilerPreset()],
        }),
        tailwindcss(),
        wayfinder({
            formVariants: true,
        }),
    ]),
    server: {
        watch: {
            ignored: [
                '**/.agents/**',
                '**/.claude/**',
                '**/.cursor/**',
                '**/.junie/**',
                '**/vendor/**',
            ],
        },
    },
    lint: {
        ignorePatterns: [
            'vendor/**',
            'node_modules/**',
            'public/**',
            'bootstrap/ssr/**',
            'tailwind.config.js',
            'resources/js/actions/**',
            'resources/js/components/ui/*',
            'resources/js/routes/**',
            'resources/js/wayfinder/**',
            // Generated by `php artisan typescript:transform`.
            'resources/js/generated/**',
        ],
        options: {
            denyWarnings: true,
            typeAware: true,
        },
    },
    fmt: {
        printWidth: 80,
        tabWidth: 4,
        singleQuote: true,
        semi: true,
        singleAttributePerLine: false,
        htmlWhitespaceSensitivity: 'css',
        ignorePatterns: [
            '.github/**',
            'composer.json',
            'resources/js/components/ui/*',
            'resources/views/mail/*',
            'resources/js/generated/**',
        ],
        sortTailwindcss: {
            functions: ['clsx', 'cn', 'cva'],
            stylesheet: 'resources/css/app.css',
        },
    },
});
